import { mkdir, copyFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_PATH || 'sharp');
const root = process.cwd();
await Promise.all(['public/brand', 'public/images'].map(p => mkdir(p, { recursive: true })));
for (const [source, target] of [
  ['ALWAFI_01_Luxury_for_Dark_OUTLINED.svg', 'alwafi-dark.svg'],
  ['ALWAFI_02_Primary_for_Light_OUTLINED.svg', 'alwafi-light.svg'],
  ['ALWAFI_07_Icon_Flat.svg', 'alwafi-icon.svg'],
]) await copyFile(source, path.join(root, 'public/brand', target));
for (const [source, target] of [
  ['Golden-Hour Arabian Architectural Development.png', 'arabian-development.webp'],
  ['Golden Hour Construction Skyline.png', 'construction-skyline.webp'],
  ['Golden Hour Riyadh Construction Panorama.png', 'riyadh-panorama.webp'],
  ['Sunlit Construction Skyline with Crane.png', 'site-engineer.webp'],
]) {
  await sharp(source).resize({ width: 1920, withoutEnlargement: true }).webp({ quality: 86, effort: 6 }).toFile(path.join(root, 'public/images', target));
}
// Art-directed crops: each section gets its own framing, and the decorative
// panels baked into the edges of the source renders are cropped away.
for (const [source, target, region] of [
  ['Golden-Hour Arabian Architectural Development.png', 'crop-hero-portrait.webp', { left: 930, top: 0, width: 742, height: 941 }],
  ['Golden-Hour Arabian Architectural Development.png', 'crop-skyline-dusk.webp', { left: 0, top: 120, width: 1180, height: 760 }],
  ['Golden Hour Construction Skyline.png', 'crop-engineer-view.webp', { left: 330, top: 0, width: 1444, height: 887 }],
  ['Golden Hour Riyadh Construction Panorama.png', 'crop-site-panorama.webp', { left: 0, top: 0, width: 1330, height: 793 }],
  ['Golden Hour Riyadh Construction Panorama.png', 'crop-lattice.webp', { left: 110, top: 0, width: 420, height: 400 }],
  ['Sunlit Construction Skyline with Crane.png', 'crop-site-plans.webp', { left: 880, top: 60, width: 792, height: 881 }],
  ['Sunlit Construction Skyline with Crane.png', 'crop-city-works.webp', { left: 300, top: 0, width: 1372, height: 900 }],
]) {
  await sharp(source).extract(region).webp({ quality: 84, effort: 6 }).toFile(path.join(root, 'public/images', target));
}
await sharp('ALWAFI_07_Icon_Flat_2400px.png').trim().resize(64,64,{fit:'contain',background:'#f7f5ef'}).png().toFile('src/app/icon.png');
await writeFile('public/images/README.md', '# Image provenance\n\nAll four architectural source PNGs were supplied by the user in the project root. Their origin and real-project status have not been verified. They are displayed as expressive architectural illustrations, never as completed ALWAFI projects. Original assets remain untouched. Derivative WebP files, including the art-directed crop-*.webp framings, are generated by scripts/prepare-assets.mjs. Confirm publication rights before launch.\n');
console.log('Prepared official supplied logos, icon, 4 compressed architectural illustrations and 7 art-directed crops.');
